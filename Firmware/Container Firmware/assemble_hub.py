"""Assemble a flashable Hub_3_1 sketch from the base files plus the module snippets in Hub_3_1/Modules.

Stand-in for the untitledspacecraft.com code tool, which only knows the upstream snippets.
Default modules and output are this controller's (see My_Controller/README.md).

usage:
  python assemble_hub.py                       # this controller -> My_Controller/Hub_3_1
  python assemble_hub.py --compile             # ... and compile it for the Arduino Micro
  python assemble_hub.py c1 h1 --out <dir>     # other module set (snippet names) or "all"
"""
import argparse
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "Hub_3_1"
DEFAULT_OUT = HERE / "My_Controller"
# Action Groups, Telemetry, Control Systems, Time, Rotation, Translation, Throttle, Executive Actions
DEFAULT_MODULES = ["h1", "c1", "g1", "b1", "f3", "f5", "f6", "a3"]
ARDUINO_CLI = pathlib.Path.home() / "AppData/Local/Programs/Arduino IDE/resources/app/lib/backend/resources/arduino-cli.exe"

HEADERS = ["Transmissions", "Enable Action", "Action Results", "Action",
           "Message Handler", "Keyboard Emulation", "definitions"]
GENERATED = "// GENERATED by assemble_hub.py from Hub_3_1 + Modules ({}). Edit the sources, not this file.\n"


def split_sections(text):
    sections = {h: [] for h in HEADERS}
    current = None
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("// ") and stripped[3:].strip() in HEADERS:
            current = stripped[3:].strip()
            continue
        if current:
            sections[current].append(line)
    return {k: "\n".join(v).strip("\n") for k, v in sections.items()}


def assemble(names, out_parent):
    out = out_parent / "Hub_3_1"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for f in SRC.iterdir():
        if f.is_file():
            shutil.copy(f, out / f.name)

    parts = {h: [] for h in HEADERS}
    cag = []
    for n in names:
        secs = split_sections((SRC / "Modules" / f"{n}.ino").read_text())
        for h in HEADERS:
            if not secs[h]:
                continue
            if h == "Message Handler" and "myAG" in secs[h]:
                cag.append(f"// --- {n} ---\n{secs[h]}")  # action-group bodies share one CAGSTATUS case
            else:
                parts[h].append(f"// --- {n} ---\n{secs[h]}")
    if cag:
        parts["Message Handler"].append(
            "    case CAGSTATUS_MESSAGE:\n"
            "      if (msgSize == sizeof(cagStatusMessage)) {\n"
            "        cagStatusMessage myAG = parseCAGStatusMessage(msg);\n"
            + "\n".join(cag) + "\n      }\n      break;")

    # A module that defines EVA_List_Analog (Translation) replaces the default one in actionResults.h.
    if any(re.search(r"^\s*(const\s+)?uint8_t EVA_List_Analog\[", s, re.M)
           for s in parts["definitions"] + parts["Action Results"]):
        ar = (SRC / "actionResults.h").read_text()
        ar, k = re.subn(r"// Default EVA_List_Analog.*?\};", "", ar, flags=re.S)
        assert k == 1
        (out / "actionResults.h").write_text(ar)

    stamp = GENERATED.format(" ".join(names))
    header = "\n\n".join(parts["Keyboard Emulation"] + parts["definitions"] + parts["Action Results"])
    (out / "modules.h").write_text(stamp + "#pragma once\n" + header + "\n")
    ino = (out / "Hub_3_1.ino").read_text()
    ino = ino.replace('#include "actionResults.h"', '#include "actionResults.h"\n#include "modules.h"', 1)
    (out / "Hub_3_1.ino").write_text(stamp + ino)

    (out / "05_Modules.ino").write_text(stamp + "\n\n".join(parts["Action"]) + "\n")

    sf = (out / "01_System_Functions.ino").read_text()
    sf, n1 = re.subn(r"(void transmissions\(\) \{.*?\*/\n)", lambda m: m.group(1) + "\n".join(parts["Transmissions"]) + "\n", sf, count=1, flags=re.S)
    sf, n2 = re.subn(r"(void actions\(\) \{\n)", lambda m: m.group(1) + "\n".join(parts["Enable Action"]) + "\n", sf, count=1)
    assert n1 == 1 and n2 == 1, (n1, n2)
    (out / "01_System_Functions.ino").write_text(sf)

    tr = (out / "02_Transmissions.ino").read_text()
    tr, n3 = re.subn(r"(void messageHandler\(.*?switch\(messageType\) \{\n)", lambda m: m.group(1) + "\n".join(parts["Message Handler"]) + "\n", tr, count=1, flags=re.S)
    assert n3 == 1
    (out / "02_Transmissions.ino").write_text(tr)
    print("assembled", out, "with", " ".join(names))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("modules", nargs="*", help='snippet names (e.g. c1 h1) or "all"; default: this controller')
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT, help="parent folder for the Hub_3_1 sketch")
    ap.add_argument("--compile", action="store_true", help="compile with arduino-cli for the Arduino Micro")
    args = ap.parse_args()

    names = args.modules or DEFAULT_MODULES
    if names == ["all"]:
        names = sorted(p.stem for p in (SRC / "Modules").glob("*.ino"))
    out = assemble(names, args.out)

    if args.compile:
        cli = shutil.which("arduino-cli") or str(ARDUINO_CLI)
        sys.exit(subprocess.call([cli, "compile", "-b", "arduino:avr:micro", str(out)]))


if __name__ == "__main__":
    main()
